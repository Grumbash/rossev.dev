// Writes src/scripts/nca/baseline.ts: the signature of the GR training target
// (scripts/nca/target.json) that the page's recovery guard judges "grown" against.
// The page does not ship the target image, only these few dozen numbers.
// Run after retraining: bun scripts/nca/gen-baseline.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { measureShape } from '../../src/scripts/nca/healer';
import { decodeWeights } from '../../src/scripts/nca/weights';

export function targetBaseline() {
  const target: { size: number; rgba: number[] } = JSON.parse(readFileSync('scripts/nca/target.json', 'utf8'));
  const bin = readFileSync('public/nca/gr.bin');
  const { aliveThreshold } = decodeWeights(bin.buffer.slice(bin.byteOffset, bin.byteOffset + bin.byteLength));
  const s = measureShape(target.rgba, target.size, aliveThreshold);
  const round = (v: number) => Math.round(v * 100) / 100;
  return {
    size: target.size,
    alive: s.alive,
    x0: s.x0,
    y0: s.y0,
    x1: s.x1,
    y1: s.y1,
    occ: Array.from(s.occ),
    green: Array.from(s.green, round),
  };
}

if (import.meta.main) {
  const b = targetBaseline();
  writeFileSync(
    'src/scripts/nca/baseline.ts',
    `// Generated by scripts/nca/gen-baseline.ts from scripts/nca/target.json; do not edit.\n` +
      `// The GR training target's signature (see measureShape in ./healer.ts), at the model's alive threshold.\n` +
      `export const GR_BASELINE = {\n` +
      Object.entries(b)
        .map(([k, v]) => `  ${k}: ${Array.isArray(v) ? `[${v.join(', ')}]` : v},\n`)
        .join('') +
      `};\n`
  );
  console.log(b);
}
